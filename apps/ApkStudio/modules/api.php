        } else if (preg_match('/android:icon="@mipmap\/([a-zA-Z0-9_]+)"/', $manifest, $matches)) {
            // Rewrite mipmap to drawable for simple uncompressed single icon asset pipeline
            $manifest = preg_replace('/android:icon="@mipmap\/[a-zA-Z0-9_]+"/', 'android:icon="@drawable/app_icon"', $manifest);
            $icon_name = 'app_icon';
