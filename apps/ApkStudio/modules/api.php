                    $updated = str_replace($old_pkg, $new_pkg, $content);
                    if ($updated !== $content) {
                        file_put_contents($filePath, $updated);
                    }
                }
            }
        }

        // 5. Update app name occurrences in strings.xml and build.sh name mappings
