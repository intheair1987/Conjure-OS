            exit;
        }

        // Clean up all existing app_icon variants (e.g. app_icon.xml, app_icon.png) to prevent AAPT2 duplicate collisions
        foreach (glob($drawable_dir . '/' . $icon_name . '.*') as $old_icon) {
            if (file_exists($old_icon)) {
                unlink($old_icon);
            }
        }

        $icon_path = $drawable_dir . '/' . $icon_name . '.png';
        file_put_contents($icon_path, $image_bytes);

        // 3. Write metadata SVG outside the compiled res/ directory to keep aapt2 clean
