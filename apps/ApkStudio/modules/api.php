// JIT Template Propagation
function propagate_ssot_templates() {
    $sync_file = __DIR__ . '/../data/template_sync.json';
    if (!file_exists($sync_file)) {
        return; // Rely exclusively on template_sync.json as the Single Source of Truth
    }

    $sync_map = json_decode(file_get_contents($sync_file), true);
    if (!$sync_map) return;

    $base_dir = realpath(__DIR__ . '/..');

    foreach ($sync_map as $master_rel => $dest_rel_list) {
        $master_abs = $base_dir . '/' . $master_rel;
        if (!file_exists($master_abs)) continue;

        $master_content = file_get_contents($master_abs);
        $ext = pathinfo($master_abs, PATHINFO_EXTENSION);

        $warning = "";
        if ($ext === 'java' || ($ext === 'tpl' && strpos($master_rel, '.java') !== false)) {
            $warning = "// ============================================================================\n"
                     . "// ⚠️ WARNING: DO NOT EDIT THIS FILE DIRECTLY!\n"
                     . "// This is a dynamically synchronized child template.\n"
                     . "// All modifications must be made strictly to the master template at:\n"
                     . "// apps/ApkStudio/" . $master_rel . "\n"
                     . "// ============================================================================\n\n";
        } elseif ($ext === 'xml' || ($ext === 'tpl' && strpos($master_rel, '.xml') !== false) || $ext === 'html' || ($ext === 'tpl' && strpos($master_rel, '.html') !== false)) {
            $warning = "<!--\n"
                     . "============================================================================\n"
                     . "⚠️ WARNING: DO NOT EDIT THIS FILE DIRECTLY!\n"
                     . "This is a dynamically synchronized child template.\n"
                     . "All modifications must be made strictly to the master template at:\n"
                     . "apps/ApkStudio/" . $master_rel . "\n"
                     . "============================================================================\n"
                     . "-->\n\n";
        }

        foreach ($dest_rel_list as $dest_rel) {
            $dest_abs = $base_dir . '/' . $dest_rel;
            $dest_dir = dirname($dest_abs);

            if (is_dir($dest_dir)) {
                if (!empty($warning) && ($ext === 'xml' || strpos($master_rel, '.xml') !== false)) {
                    if (preg_match('/^\s*(<\?xml[^>]*\?>)/i', $master_content, $matches)) {
                        $xml_decl = $matches[1];
                        $body = substr($master_content, strlen($matches[0]));
                        $final_content = $xml_decl . "\n" . $warning . ltrim($body);
                    } else {
                        $final_content = $warning . $master_content;
                    }
                } else {
                    $final_content = $warning . $master_content;
                }

                if (!file_exists($dest_abs) || file_get_contents($dest_abs) !== $final_content) {
                    file_put_contents($dest_abs, $final_content);
                }
            }
        }
    }
}

