// Adaptive Path Resolver
function get_project_dir($name, $id) {
    $safe_name = preg_replace('/[^a-zA-Z0-9_-]/', '', $name);
    $path1 = __DIR__ . "/../data/projects/{$safe_name}";
    $path2 = __DIR__ . "/../data/projects/{$safe_name}_{$id}";
    if (is_dir($path1)) {
        return realpath($path1);
    }
    if (is_dir($path2)) {
        return realpath($path2);
    }
    return false;
}

// Two-Way Filesystem Sync Engine
function sync_projects_from_filesystem($db) {
    $projects_dir = __DIR__ . '/../data/projects';
    if (!is_dir($projects_dir)) {
        mkdir($projects_dir, 0777, true);
        return;
    }
    
    $dirs = glob($projects_dir . '/*', GLOB_ONLYDIR);
    $active_ids = [];
    
    foreach ($dirs as $dir) {
        $folder_name = basename($dir);
        if (strpos($folder_name, '.') === 0) continue;
        
        $id_part = null;
        $name_part = $folder_name;
        
        // Parse legacy suffix if present
        if (preg_match('/^(.+)_(\d+)$/', $folder_name, $matches)) {
            $name_part = $matches[1];
            $id_part = (int)$matches[2];
        }
        
        // Inspect AndroidManifest to automatically recover package names
        $pkg = 'com.example.' . strtolower(preg_replace('/[^a-zA-Z0-9]/', '', $name_part));
        $manifest_path = "$dir/AndroidManifest.xml";
        if (file_exists($manifest_path)) {
            $manifest_content = file_get_contents($manifest_path);
            if (preg_match('/package="([^"]+)"/', $manifest_content, $pkg_matches)) {
                $pkg = $pkg_matches[1];
            }
        }
        
        if ($id_part !== null) {
            $stmt = $db->prepare("SELECT COUNT(*) FROM projects WHERE id = ?");
            $stmt->execute([$id_part]);
            if ($stmt->fetchColumn() == 0) {
                $stmt = $db->prepare("INSERT INTO projects (id, name, package_name) VALUES (?, ?, ?)");
                $stmt->execute([$id_part, $name_part, $pkg]);
            }
            $active_ids[] = $id_part;
        } else {
            $stmt = $db->prepare("SELECT id FROM projects WHERE name = ?");
            $stmt->execute([$name_part]);
            $row = $stmt->fetch();
            if (!$row) {
                // Auto-register newly patched folders
                $stmt = $db->prepare("INSERT INTO projects (name, package_name) VALUES (?, ?)");
                $stmt->execute([$name_part, $pkg]);
                $active_ids[] = $db->lastInsertId();
            } else {
                $active_ids[] = $row['id'];
            }
        }
    }
    
    // Prune orphans
    $stmt = $db->query("SELECT id, name FROM projects");
    $db_projects = $stmt->fetchAll();
    foreach ($db_projects as $p) {
        if (!in_array($p['id'], $active_ids)) {
            $safe_name = preg_replace('/[^a-zA-Z0-9_-]/', '', $p['name']);
            $path1 = $projects_dir . '/' . $safe_name;
            $path2 = $projects_dir . '/' . $safe_name . '_' . $p['id'];
            if (!is_dir($path1) && !is_dir($path2)) {
                $db->prepare("DELETE FROM projects WHERE id = ?")->execute([$p['id']]);
            }
        }
    }
}

function delete_dir($dir) {
    if (!is_dir($dir)) return;
    $files = array_diff(scandir($dir), ['.', '..']);
    foreach ($files as $file) {
        (is_dir("$dir/$file")) ? delete_dir("$dir/$file") : unlink("$dir/$file");
    }
    rmdir($dir);
}

function prune_empty_dirs($dir, $stop_at) {
    if (!is_dir($dir) || realpath($dir) === realpath($stop_at)) return;
    $files = array_diff(scandir($dir), ['.', '..']);
    if (empty($files)) {
        rmdir($dir);
        prune_empty_dirs(dirname($dir), $stop_at);
    }
}

function get_project_last_modified($dir) {
    if (!is_dir($dir)) return 0;
    $max_mtime = filemtime($dir);
    try {
        $iterator = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($dir, RecursiveDirectoryIterator::SKIP_DOTS),
            RecursiveIteratorIterator::SELF_FIRST
        );
        foreach ($iterator as $file) {
            if ($file->isFile()) {
                $mtime = $file->getMTime();
                if ($mtime > $max_mtime) {
                    $max_mtime = $mtime;
                }
            }
        }
    } catch (Exception $e) {
        // Fallback safely
    }
    return $max_mtime;
}

// JIT Template Hydration (SSOT Enforcement)
function enforce_ssot_templates($proj, $proj_dir) {
    // Force template propagation at the start of the build/packaging pipeline
    propagate_ssot_templates();

    $tpl_dir = __DIR__ . "/../templates";
    $replacements = [
        '{{APP_NAME}}' => $proj['name'], 
        '{{PACKAGE_NAME}}' => $proj['package_name'],
        '{{WRAPPER_URL}}' => $proj['wrapper_url'] ?? '',
        '{{DOWNLOAD_URL}}' => ''
    ];
    
    $pkg_path = "$proj_dir/src/" . str_replace('.', '/', $proj['package_name']);
    if (!is_dir($pkg_path)) mkdir($pkg_path, 0777, true);
    if (!is_dir("$proj_dir/res/values")) mkdir("$proj_dir/res/values", 0777, true);
    
    if (($proj['project_type'] ?? '') === 'wrapper') {
        $manifest_content = file_get_contents("$tpl_dir/AndroidManifest_wrapper.xml.tpl");
        $hydrated_manifest = strtr($manifest_content, $replacements);
        
        // Dynamically recover/preserve custom launcher icon attributes if the asset exists on disk!
        $drawable_dir = "$proj_dir/res/drawable";
        if (is_dir($drawable_dir)) {
            $files = glob("$drawable_dir/*.png");
            if (!empty($files)) {
                $icon_name = pathinfo($files[0], PATHINFO_FILENAME);
                if (strpos($hydrated_manifest, 'android:icon=') !== false) {
                    $hydrated_manifest = preg_replace('/android:icon="[^"]+"/', 'android:icon="@drawable/' . $icon_name . '"', $hydrated_manifest);
                } else {
                    $hydrated_manifest = preg_replace('/<application/i', '<application android:icon="@drawable/' . $icon_name . '"', $hydrated_manifest);
                }
            }
        }
        
        file_put_contents("$proj_dir/AndroidManifest.xml", $hydrated_manifest);
        file_put_contents("$pkg_path/MainActivity.java", strtr(file_get_contents("$tpl_dir/MainActivity_wrapper.java.tpl"), $replacements));
        if (!is_dir("$proj_dir/assets")) mkdir("$proj_dir/assets", 0777, true);
        if (file_exists("$tpl_dir/settings.html.tpl")) {
            file_put_contents("$proj_dir/assets/settings.html", strtr(file_get_contents("$tpl_dir/settings.html.tpl"), $replacements));
        }
    }
    
    // Always JIT-hydrate strings.xml if missing
    if (!file_exists("$proj_dir/res/values/strings.xml")) {
        file_put_contents("$proj_dir/res/values/strings.xml", strtr(file_get_contents("$tpl_dir/strings.xml.tpl"), $replacements));
    }
    // Only JIT-hydrate build.sh always for wrapper projects, or if it doesn't exist for standard projects (preserving custom builds like BuildKernel)
    if (($proj['project_type'] ?? '') === 'wrapper' || !file_exists("$proj_dir/build.sh")) {
        file_put_contents("$proj_dir/build.sh", strtr(file_get_contents("$tpl_dir/build.sh.tpl"), $replacements));
        chmod("$proj_dir/build.sh", 0755);
    }
}

