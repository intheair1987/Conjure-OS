function sc_clean_logic($path) {
    if (!file_exists($path)) return "// Logic file missing: $path";
    $content = file_get_contents($path);
    // 1. Remove opening tag and any immediate whitespace/newlines
    $content = preg_replace('/^<\?php\s*/i', '', $content);
    // 2. Remove closing tag and any trailing whitespace
    $content = preg_replace('/\s*\?>\s*$/', '', $content);
    return trim($content);
}

