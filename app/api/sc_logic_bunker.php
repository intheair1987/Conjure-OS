        function startBunkerProgressPolling() {
            if (scPollInterval || !scTrackTimestamp) return;
            scPollInterval = setInterval(async () => {
                try {
                    const res = await fetch(`recovery.php?ajax=progress&timestamp=${scTrackTimestamp}`);
                    const data = await res.json();
                    if (data.status === 'success' && data.size > 0) {
                        const sizeMb = (data.size / (1024 * 1024)).toFixed(2);
                        
                        if (data.is_final) {
                            if (data.size === scLastSize) {
                                scStallCount++;
                                if (scStallCount >= 4) { // Stable for 4 seconds
                                    clearInterval(scPollInterval);
                                    scPollInterval = null;
                                    window.location.href = 'recovery.php?msg=NEW+CHECKPOINT+SECURED';
                                    return;
                                }
                            } else {
                                scLastSize = data.size;
                                scStallCount = 0;
                            }
                        } else {
                            scLastSize = data.size;
                            scStallCount = 0;
                        }
                        
                        updateBunkerProgress(95, `COMPRESSING (${sizeMb} MB / ~${scTargetMb} MB est.)...`);
                    }
                } catch (e) {}
            }, 1000);
        }

